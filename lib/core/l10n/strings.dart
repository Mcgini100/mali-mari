  final AppLanguage language;

  Map<K, String> get _table => switch (language) {
        AppLanguage.en => _en,
        AppLanguage.sn => _sn,
        AppLanguage.nd => _nd,
      };

  String operator [](K key) => _table[key] ?? _en[key] ?? key.name;

  String f(K key, Map<String, String> args) {
    var s = this[key];
    args.forEach((name, value) => s = s.replaceAll('{$name}', value));
    return s;
  }

  String month(int month) => _months[language]![month - 1];

  /// Short month for compact labels. Shona and Ndebele month names share
  /// prefixes (Chikumi, Chikunguru), so only English is abbreviated.
  String monthShort(int month) {
    final full = this.month(month);
    return language == AppLanguage.en ? full.substring(0, 3) : full;
  }

  String weekday(int weekday) => _weekdays[language]![weekday - 1];

  String monthYear(MonthRange m) => '${month(m.month)} ${m.year}';

  /// "Saturday, 10 October"
  String longDate(DateTime d) => '${weekday(d.weekday)}, ${d.day} ${month(d.month)}';

  /// "Today", "Yesterday", or "Thu 8 Oct".
  String dayLabel(DateTime d, DateTime now) {
    final diff = daysBetween(d, now);
    if (diff == 0) return this[K.today];
    if (diff == 1) return this[K.yesterday];
    final wd = weekday(d.weekday);
    final shortWd = language == AppLanguage.en ? wd.substring(0, 3) : wd;
    return '$shortWd ${d.day} ${monthShort(d.month)}';
  }

  String time(DateTime d) => '${d.hour.toString().padLeft(2, '0')}:${d.minute.toString().padLeft(2, '0')}';
}
